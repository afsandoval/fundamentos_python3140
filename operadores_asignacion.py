#OPERADORES DE ASIGNACION --------------


#ASIGNACION =

x = 5
print(x)

# ASIGNACION CON SUMA  
x = x + 2
x += 2
print(x)

#ASIGNACION CON RESTA
x = x - 3
x -= 3
print(x)

#ASIGNACION CON MULTIPLICACION
x = x * 4
x *= 4
print(x)

#ASIGNACION CON DIVISION
x = x / 2
x /= 2
print(x)

#ASIGNACION CON DIVISION ENTERA
x = x // 2
x //= 2
print(x)

#ASIGNACION CON MODULO
x = x % 3
x %= 3
print(x)

#ASIGNACION CON POTENCIA
x = x ** 2
x **= 2
print(x)

# EJERCICIO: PRODUCTO CON DESCUENTO
precio = 100000
descuento = 0.5

precio_final = precio - (precio * descuento)
print(precio_final)


